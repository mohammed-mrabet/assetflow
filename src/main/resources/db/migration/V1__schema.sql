-- Schéma AssetFlow : PLM (articles, nomenclatures versionnées) et EAM (équipements, maintenance)

create table item (
    id             bigint generated by default as identity primary key,
    code           varchar(40)  not null unique,
    name           varchar(120) not null,
    type           varchar(20)  not null check (type in ('ASSEMBLY', 'PART')),
    stock_quantity integer      not null default 0 check (stock_quantity >= 0),
    min_stock      integer      not null default 0 check (min_stock >= 0)
);

create table bom_revision (
    id          bigint generated by default as identity primary key,
    item_id     bigint      not null references item (id),
    revision    varchar(5)  not null,
    status      varchar(20) not null check (status in ('DRAFT', 'RELEASED', 'OBSOLETE')),
    released_at timestamp(6) with time zone,
    unique (item_id, revision)
);

create table bom_line (
    id            bigint generated by default as identity primary key,
    bom_id        bigint  not null references bom_revision (id) on delete cascade,
    child_item_id bigint  not null references item (id),
    quantity      integer not null check (quantity > 0),
    unique (bom_id, child_item_id)
);

create table asset (
    id              bigint generated by default as identity primary key,
    code            varchar(40)  not null unique,
    name            varchar(120) not null,
    location        varchar(120),
    criticality     varchar(1)   not null check (criticality in ('A', 'B', 'C')),
    status          varchar(20)  not null check (status in ('IN_SERVICE', 'DOWN', 'RETIRED')),
    commissioned_on date         not null,
    model_item_id   bigint references item (id)
);

create table preventive_plan (
    id            bigint generated by default as identity primary key,
    asset_id      bigint       not null references asset (id),
    title         varchar(120) not null,
    interval_days integer      not null check (interval_days > 0),
    last_done_on  date,
    active        boolean      not null default true
);

create table work_order (
    id            bigint generated by default as identity primary key,
    asset_id      bigint      not null references asset (id),
    plan_id       bigint references preventive_plan (id),
    type          varchar(20) not null check (type in ('CORRECTIVE', 'PREVENTIVE')),
    priority      varchar(2)  not null check (priority in ('P1', 'P2', 'P3')),
    status        varchar(20) not null check (status in ('CREATED', 'PLANNED', 'IN_PROGRESS', 'DONE', 'CLOSED', 'CANCELLED')),
    description   varchar(500) not null,
    asset_stopped boolean     not null default false,
    failure_at    timestamp(6) with time zone,
    created_at    timestamp(6) with time zone not null,
    planned_for   date,
    started_at    timestamp(6) with time zone,
    completed_at  timestamp(6) with time zone,
    report        varchar(1000),
    version       bigint      not null default 0
);

create table work_order_part (
    id            bigint generated by default as identity primary key,
    work_order_id bigint  not null references work_order (id) on delete cascade,
    item_id       bigint  not null references item (id),
    quantity      integer not null check (quantity > 0)
);

create index idx_work_order_asset on work_order (asset_id);
create index idx_work_order_plan_status on work_order (plan_id, status);
create index idx_bom_revision_item_status on bom_revision (item_id, status);
